let lineSequence = 0;

function line(accountId, debitCents, creditCents, description) {
  lineSequence += 1;
  return {
    id: `line-${lineSequence}`,
    lineNo: lineSequence,
    accountId,
    description,
    debitCents,
    creditCents,
  };
}

